// Description of |3474. Lexicographically Smallest Generated String|:
//
// You are given two strings, |str1| and |str2|, of lengths |n| and |m|,
// respectively. A string |word| of length |n + m - 1| is defined to be
// generated by |str1| and |str2| if it satisfies the following conditions for
// each index |0 <= i <= n - 1|:
//
//  • If |str1[i] == 'T'|, the substring of |word| with size |m| starting at
//  index |i| is equal to |str2|, i.e., |word[i..(i + m - 1)] == str2|.
//
//  • If |str1[i] == 'F'|, the substring of |word| with size |m| starting at
//  index |i| is not equal to |str2|, i.e., |word[i..(i + m - 1)] != str2|.
// Return the lexicographically smallest possible string that can be generated
// by |str1| and |str2|. If no string can be generated, return an empty string
// |""|.
//
//

LEETCODE_BEGIN_RESOLVING(3474, LexicographicallySmallestGeneratedString,
                         Solution);

class Solution {
public:
  string generateString(string s, string t) {
    int    n = s.size(), m = t.size();
    string ans(n + m - 1, '?');
    for (int i = 0; i < n; i++) {
      if (s[i] != 'T') {
        continue;
      }
      for (int j = 0; j < m; j++) {
        char v = ans[i + j];
        if (v != '?' && v != t[j]) {
          return "";
        }
        ans[i + j] = t[j];
      }
    }

    string old_ans = ans;
    for (char &c : ans) {
      if (c == '?') {
        c = 'a';
      }
    }

    for (int i = 0; i < n; i++) {
      if (s[i] != 'F') {
        continue;
      }
      if (string(ans.begin() + i, ans.begin() + i + m) != t) {
        continue;
      }
      bool ok = false;
      for (int j = i + m - 1; j >= i; j--) {
        if (old_ans[j] == '?') {
          ans[j] = 'b';
          ok     = true;
          break;
        }
      }
      if (!ok) {
        return "";
      }
    }

    return ans;
  }
};

LEETCODE_END_RESOLVING(Solution);

